# --- Voice-detection model pool ----------------------------------------------------
# SileroVADAnalyzer builds a fresh ONNX InferenceSession in its constructor and Pipecat
# does not cache it, so building one per call costs ~220 ms of dead air before Mia can
# speak. Measured across three consecutive calls: 386/349/375 ms — it never gets cheaper.
#
# The analyzer holds per-stream state, so a single shared instance would corrupt two
# simultaneous calls. A small pool gives each call its own instance while paying the
# construction cost at container startup instead of while somebody is listening to silence.
VAD_STOP_SECS = float(os.getenv("VAD_STOP_SECS", "0.2"))

# How long the turn model waits before giving up and ending the turn on silence alone.
# Pipecat's default is 3 seconds, and it is paid in full every time the model decides the
# caller "isn't finished" — which it does often on 8 kHz phone audio, even for plainly
# complete sentences like "I want to book an appointment". Three seconds of dead air reads
# as a broken line: on the first real call the caller gave up and said "hello?" before Mia
# answered. One second still covers a genuine mid-sentence pause without stranding anyone.
SMART_TURN_STOP_SECS = float(os.getenv("SMART_TURN_STOP_SECS", "1.0"))
VAD_POOL_SIZE = int(os.getenv("VAD_POOL_SIZE", "2"))

_vad_pool: list[SileroVADAnalyzer] = []
_vad_lock = threading.Lock()


def _new_vad() -> SileroVADAnalyzer:
    return SileroVADAnalyzer(params=VADParams(stop_secs=VAD_STOP_SECS))


def _prewarm_vad_pool() -> None:
    """Fill the pool at import, so the first caller doesn't wait for a model load."""
    _refill_vad_pool()
    logger.info(f"VAD pool warm ({VAD_POOL_SIZE} ready)")


def _refill_vad_pool() -> None:
    """Top the pool back up in the background, after a call has taken one."""
    while True:
        with _vad_lock:
            if len(_vad_pool) >= VAD_POOL_SIZE:
                return
        vad = _new_vad()  # built outside the lock; it takes ~220 ms
        with _vad_lock:
            _vad_pool.append(vad)


def acquire_vad() -> SileroVADAnalyzer:
    """Take a fresh analyzer, and start building a replacement in the background.

    A used analyzer is never returned to the pool. It carries state across a call —
    leftover audio in ``_vad_buffer``, the current ``_vad_state``, the speech start/stop
    counters and the smoothed volume — and exposes no public reset. Handing that to the
    next caller could make Mia think somebody is already speaking when the call opens.
    So each call consumes one and the pool refills off the critical path.
    """
    with _vad_lock:
        vad = _vad_pool.pop() if _vad_pool else None

    threading.Thread(target=_refill_vad_pool, daemon=True).start()

    if vad is None:
        logger.debug("VAD pool empty — building one for this call")
        return _new_vad()
    return vad


# Daemon so it never holds up shutdown. Runs at import, which on Heroku is dyno boot.
threading.Thread(target=_prewarm_vad_pool, daemon=True).start()

