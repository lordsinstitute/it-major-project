def build_system_prompt() -> str:
    """Mia's prompt, rebuilt per call so she knows the current UK time.

    Whether the practice is open is worked out here rather than left to the model — it is
    the kind of thing an LLM gets subtly wrong, and it costs nothing to compute.
    """
    now = datetime.now(ZoneInfo("Europe/London"))
    weekday = now.weekday()  # Monday is 0
    open_now = weekday < 5 and 8 <= now.hour < 18

    if open_now:
        status = (
            f"The practice is OPEN right now. It closes at six this evening, which is in "
            f"about {_spoken_hours_until(now)}."
        )
    elif weekday < 5 and now.hour < 8:
        status = "The practice is CLOSED right now. It opens at eight this morning."
    elif weekday == 4:
        # Friday after closing — "tomorrow" would be Saturday, when we are shut.
        status = (
            "The practice is CLOSED for today, and closed all weekend. It opens again on "
            "Monday at eight in the morning."
        )
    elif weekday < 5:
        status = "The practice is CLOSED for today. It opens again at eight tomorrow morning."
    else:
        status = (
            "The practice is CLOSED for the weekend. It opens again on Monday at eight "
            "in the morning."
        )

    return (
        f"{MIA_BEHAVIOUR}\n\n"
        f"Right now it is {now.strftime('%A')}, {now.day} {now.strftime('%B')}, "
        f"at {now.strftime('%I:%M %p').lstrip('0').lower()} UK time.\n"
        f"{status}\n"
        f"Use this if someone asks whether you are open, or when you close. Do not read the "
        f"date out unless they ask for it.\n\n"
        f"{BUSINESS_FACTS}"
    )


def _spoken_hours_until(now: datetime) -> str:
    """How long until six in the evening, phrased for speech."""
    minutes = (18 - now.hour) * 60 - now.minute
    if minutes <= 60:
        return f"{minutes} minutes"
    hours, mins = divmod(minutes, 60)
    if mins < 15:
        return f"{hours} hours"
    if mins < 45:
        return f"{hours} and a half hours"
    return f"{hours + 1} hours"


