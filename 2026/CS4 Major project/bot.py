# Deepgram runs a European endpoint that the same API key works on. Which one is closer
# depends entirely on where this is deployed: from London the EU endpoint is a local hop and
# the US one is an ocean away. Deepgram answers twice per turn (ears, then voice), so this is
# four of the six network legs in a single reply — the largest latency lever we have.
# Set DEEPGRAM_HOST=api.deepgram.com to go back to the US endpoint.
DEEPGRAM_HOST = os.getenv("DEEPGRAM_HOST", "api.eu.deepgram.com")


def build_tts():
    """Build the TTS service named by TTS_PROVIDER in .env.

    Both are WebSocket streaming services with interruption support, so the pipeline
    behaves the same either way — only the voice and the bill change.

    deepgram    Aura-2. Billed against the same $200 Deepgram credit as speech-to-text,
                at $0.03/1k characters. Roughly 12,500 minutes of calls.
    elevenlabs  Flash v2.5. Separate account, and the free tier is only ~50 minutes
                of calls and is non-commercial.
    """
    provider = os.getenv("TTS_PROVIDER", "deepgram").strip().lower()

    if provider == "elevenlabs":
        logger.info("TTS: ElevenLabs Flash v2.5")
        return ElevenLabsTTSService(
            api_key=os.getenv("ELEVENLABS_API_KEY"),
            settings=ElevenLabsTTSService.Settings(
                # "Alice" — British female.
                voice=os.getenv("ELEVENLABS_VOICE_ID", "Xb7hH8MSUJpSbSDYk0k2"),
                model="eleven_flash_v2_5",  # lowest-latency ElevenLabs model
                stability=0.5,
                speed=1.0,
            ),
        )

    if provider != "deepgram":
        logger.warning(f"Unknown TTS_PROVIDER '{provider}' — falling back to deepgram")

    # British female Aura voices: aura-2-pandora-en, aura-athena-en (both "smooth, calm").
    voice = os.getenv("DEEPGRAM_VOICE", "aura-2-pandora-en")
    logger.info(f"TTS: Deepgram Aura ({voice})")
    return DeepgramTTSService(
        api_key=os.getenv("DEEPGRAM_API_KEY"),
        base_url=f"wss://{DEEPGRAM_HOST}",
        settings=DeepgramTTSService.Settings(voice=voice),
    )


async def start_recording(call_sid: str | None) -> None:
    """Ask Twilio to record this call leg, so testers can be rung back for feedback.

    Uses the Calls Recordings REST subresource, which attaches to the call leg and so
    coexists with <Connect><Stream>. The <Record> TwiML verb does not — don't use it.

    Recordings appear in Twilio Console -> Monitor -> Logs -> Recordings, already linked
    to the caller's number. A failure here must never take down the call.
    """
    if not call_sid:
        return

    account_sid = os.getenv("TWILIO_ACCOUNT_SID")
    auth_token = os.getenv("TWILIO_AUTH_TOKEN")
    if not account_sid or not auth_token:
        logger.warning("No Twilio credentials — skipping call recording")
        return

    url = f"https://api.twilio.com/2010-04-01/Accounts/{account_sid}/Calls/{call_sid}/Recordings.json"
    try:
        auth = aiohttp.BasicAuth(account_sid, auth_token)
        data = {"RecordingChannels": "dual", "RecordingTrack": "both"}
        async with aiohttp.ClientSession() as session:
            async with session.post(url, auth=auth, data=data) as response:
                if response.status in (200, 201):
                    logger.info("Recording started")
                else:
                    logger.warning(
                        f"Could not start recording ({response.status}): {await response.text()}"
                    )
    except Exception as e:
        logger.warning(f"Could not start recording: {e}")


async def run_bot(transport: BaseTransport, runner_args: RunnerArguments) -> None:
    """The pipeline. Identical for the browser and the phone."""
    telephony = isinstance(runner_args, WebSocketRunnerArguments)

    # endpointing: ms of silence before Deepgram finalises a transcript (default 10).
    # utterance_end_ms: how long it waits before declaring the utterance over (default 1000).
    # Both are pure waiting, so they come straight off the front of every reply.
    stt = DeepgramSTTService(
        api_key=os.getenv("DEEPGRAM_API_KEY"),
        base_url=DEEPGRAM_HOST,
        settings=DeepgramSTTService.Settings(
            endpointing=int(os.getenv("STT_ENDPOINTING_MS", "150")),
            utterance_end_ms=int(os.getenv("STT_UTTERANCE_END_MS", "1000")),
            interim_results=True,  # required for utterance_end_ms, and speeds up turn detection
        ),
    )

    llm = OpenAILLMService(
        api_key=os.getenv("OPENAI_API_KEY"),
        settings=OpenAILLMService.Settings(
            model=os.getenv("LLM_MODEL", "gpt-4o-mini"),
            system_instruction=build_system_prompt(),
            # Mia should answer in one or two sentences. Capping this stops a rambling
            # reply dragging out the TTS, and keeps her on-brief.
            max_completion_tokens=120,
        ),
    )

    tts = build_tts()

    # NOTE: the VAD analyzer belongs here, NOT on TransportParams. Putting it in the wrong
    # place raises no error — it silently breaks barge-in. See README.md.
    #
    # stop_secs is the silence Silero waits through before deciding the caller has finished.
    # It is paid on every single turn, so it is the cheapest latency win available — but drop
    # it too far and Mia starts talking over people who simply paused mid-sentence.
    vad = acquire_vad()
    context = LLMContext()
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(
            vad_analyzer=vad,
            # Fires on_user_turn_idle when the caller says nothing for this long after
            # Mia stops speaking. Guards against dead lines left off the hook.
            user_idle_timeout=SILENCE_HANGUP_SECS,
            # Same strategies Pipecat uses by default, except the turn model's silence
            # fallback is shortened from 3s to SMART_TURN_STOP_SECS. The start strategies
            # are passed through unchanged — they are what make barge-in work.
            user_turn_strategies=UserTurnStrategies(
                start=default_user_turn_start_strategies(),
                stop=[
                    TurnAnalyzerUserTurnStopStrategy(
                        turn_analyzer=LocalSmartTurnAnalyzerV3(
                            params=SmartTurnParams(stop_secs=SMART_TURN_STOP_SECS)
                        )
                    )
                ],
            ),
        ),
    )

    pipeline = Pipeline(
        [
            transport.input(),
            stt,
            user_aggregator,
            llm,
            tts,
            transport.output(),
            assistant_aggregator,
        ]
    )

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(
            audio_in_sample_rate=(
                TELEPHONY_SAMPLE_RATE if telephony else DEFAULT_IN_SAMPLE_RATE
            ),
            audio_out_sample_rate=(
                TELEPHONY_SAMPLE_RATE if telephony else DEFAULT_OUT_SAMPLE_RATE
            ),
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        idle_timeout_secs=runner_args.pipeline_idle_timeout_secs,
    )

    # handle_sigint comes from the runner because uvicorn owns keyboard interrupts.
    runner = WorkerRunner(handle_sigint=runner_args.handle_sigint, force_gc=True)
    await runner.add_workers(worker)

    watchdogs: list[asyncio.Task] = []

    # Guards against ending the call twice — e.g. the time limit expiring while the
    # silence timer is already saying goodbye.
    ending = asyncio.Event()

    async def end_call(reason: str, farewell: str | None = None) -> None:
        """Say a closing line, then end the call cleanly.

        EndFrame flows to the end of the pipeline, which lets the TTS finish speaking
        first. TwilioFrameSerializer then hangs up the real call leg by itself.
        """
        if ending.is_set():
            return
        ending.set()
        logger.info(f"Ending call: {reason}")
        frames = [TTSSpeakFrame(farewell)] if farewell else []
        frames.append(EndFrame())
        await worker.queue_frames(frames)

    async def time_limit_watchdog() -> None:
        """Hard cap on call length. This is a demo line, not an unmetered phone service."""
        await asyncio.sleep(MAX_CALL_SECS)
        await end_call(f"reached {MAX_CALL_SECS:.0f}s time limit", TIMEUP_GOODBYE)

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Caller connected")
        # Speak the greeting directly rather than asking the LLM for it. This guarantees
        # the exact wording and saves an LLM round-trip at the start of the call.
        #
        # Do NOT also add this to the context by hand. The assistant aggregator sits after
        # transport.output() precisely so it collects spoken text itself — adding it here
        # too puts the greeting in the context twice.
        await worker.queue_frames([TTSSpeakFrame(build_greeting())])
        watchdogs.append(asyncio.create_task(time_limit_watchdog()))

    @user_aggregator.event_handler("on_user_turn_idle")
    async def on_user_turn_idle(aggregator):
        await end_call(f"caller silent for {SILENCE_HANGUP_SECS:.0f}s", SILENCE_GOODBYE)

    @worker.event_handler("on_pipeline_error")
    async def on_pipeline_error(worker, frame):
        # A failing service (expired API credit, rate limit, network blip) otherwise just
        # logs and leaves the caller listening to nothing. Say something and hang up.
        logger.error(f"Pipeline error: {frame}")
        await end_call("pipeline error", TROUBLE_GOODBYE)

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Caller disconnected")
        ending.set()
        await runner.cancel()

    try:
        await runner.run()
    finally:
        for task in watchdogs:
            task.cancel()


async def bot(runner_args: RunnerArguments) -> None:
    """Entry point called by Pipecat's runner."""
    transport = await create_transport(runner_args, transport_params)

    # Phone calls only: log who called and start the recording.
    #
    # Fire-and-forget, never awaited. start_recording() is a REST round-trip from this
    # container to Twilio's US API, and awaiting it delayed the whole pipeline — the caller
    # heard silence while we asked Twilio to press record. Nothing about the conversation
    # depends on the answer, and the function swallows its own failures, so let it run in
    # the background while the pipeline comes up.
    call_data = runner_args.call_data
    if call_data:
        logger.info(f"Incoming call from {call_data.from_number} to {call_data.to_number}")
        if os.getenv("RECORD_CALLS", "true").lower() == "true":
            asyncio.create_task(start_recording(call_data.call_id))

    await run_bot(transport, runner_args)


