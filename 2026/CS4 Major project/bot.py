def build_greeting() -> str:
    """The opening line, spoken the moment the call connects.

    Time-aware, because a real receptionist doesn't say the same thing at eight in the
    morning and five in the afternoon. Spoken directly rather than generated by the LLM, so
    the wording is guaranteed and there is no model round-trip before she speaks.
    """
    hour = datetime.now(ZoneInfo("Europe/London")).hour
    if hour < 12:
        part = "Good morning"
    elif hour < 17:
        part = "Good afternoon"
    else:
        part = "Good evening"
    return f"{part}, Bright Smiles Dental, Mia speaking. How can I help?"


